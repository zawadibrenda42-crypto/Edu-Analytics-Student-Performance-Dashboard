/* EXPORT STUDENTS TO CSV */

function exportToCSV(studentList) {

    if (!studentList || studentList.length === 0) {
        alert("There are no student records to export.");
        return;
    }


    const headers = [
        "ID",
        "Student Name",
        "Gender",
        "Maths",
        "English",
        "Swahili",
        "Chemistry",
        "Biology",
        "Physics",
        "Geography",
        "HomeScience",
        "Average",
        "Grade",
        "Performance"
    ];


    const rows = studentList.map(function (student) {

        return [
            student.ID || student.id || "",
            student.Name ||
                student.name ||
                student["Student Name"] ||
                "",
            student.Gender || student.gender || "",
            student.Maths || "",
            student.English || "",
            student.Swahili || "",
            student.Chemistry || "",
            student.Biology || "",
            student.Physics || "",
            student.Geography || "",
            student.HomeScience || "",
            student.average || "",
            student.grade || "",
            student.performance || ""
        ];

    });


    const csvContent = [
        headers,
        ...rows
    ]
        .map(function (row) {

            return row
                .map(function (value) {

                    const text = String(value);

                    return '"' +
                        text.replace(/"/g, '""') +
                        '"';

                })
                .join(",");

        })
        .join("\n");


    const blob = new Blob(
        [csvContent],
        {
            type: "text/csv;charset=utf-8;"
        }
    );


    downloadFile(
        blob,
        "student-performance-report.csv"
    );

}


/* EXPORT STUDENTS TO EXCEL */

function exportToExcel(studentList) {

    if (!studentList || studentList.length === 0) {
        alert("There are no student records to export.");
        return;
    }


    if (typeof XLSX === "undefined") {

        alert(
            "Excel export is not available yet. " +
            "The Excel library needs to be connected."
        );

        return;
    }


    const exportData = studentList.map(function (student) {

        return {

            ID:
                student.ID ||
                student.id ||
                "",

            "Student Name":
                student.Name ||
                student.name ||
                student["Student Name"] ||
                "",

            Gender:
                student.Gender ||
                student.gender ||
                "",

            Maths: student.Maths || "",
            English: student.English || "",
            Swahili: student.Swahili || "",
            Chemistry: student.Chemistry || "",
            Biology: student.Biology || "",
            Physics: student.Physics || "",
            Geography: student.Geography || "",
            HomeScience: student.HomeScience || "",

            Average: student.average || "",
            Grade: student.grade || "",
            Performance: student.performance || ""

        };

    });


    const worksheet =
        XLSX.utils.json_to_sheet(exportData);


    const workbook =
        XLSX.utils.book_new();


    XLSX.utils.book_append_sheet(
        workbook,
        worksheet,
        "Student Results"
    );


    XLSX.writeFile(
        workbook,
        "student-performance-report.xlsx"
    );

}


/* EXPORT STUDENTS TO PDF */

function exportToPDF(studentList) {

    if (!studentList || studentList.length === 0) {

        alert(
            "There are no student records to export."
        );

        return;
    }


    if (
        typeof window.jspdf === "undefined"
    ) {

        alert(
            "PDF export is not available yet. " +
            "The PDF library needs to be connected."
        );

        return;
    }


    const jsPDF = window.jspdf.jsPDF;

    const doc = new jsPDF({
        orientation: "landscape",
        unit: "mm",
        format: "a4"
    });


    doc.setFontSize(18);

    doc.text(
        "Student Performance Report",
        14,
        15
    );


    doc.setFontSize(10);

    doc.text(
        "Generated by Student Performance Analysis System",
        14,
        22
    );


    const tableData = studentList.map(function (student) {

        return [

            student.ID ||
                student.id ||
                "",

            student.Name ||
                student.name ||
                student["Student Name"] ||
                "",

            student.Gender ||
                student.gender ||
                "",

            student.Maths || "",
            student.English || "",
            student.Swahili || "",
            student.Chemistry || "",
            student.Biology || "",
            student.Physics || "",
            student.Geography || "",
            student.HomeScience || "",

            student.average
                ? Number(student.average).toFixed(2)
                : "",

            student.grade || "",

            student.performance || ""

        ];

    });


    if (
        typeof doc.autoTable !== "function"
    ) {

        alert(
            "PDF table support is not connected yet."
        );

        return;
    }


    doc.autoTable({

        head: [[
            "ID",
            "Name",
            "Gender",
            "Maths",
            "English",
            "Swahili",
            "Chemistry",
            "Biology",
            "Physics",
            "Geography",
            "HomeScience",
            "Average",
            "Grade",
            "Performance"
        ]],

        body: tableData,

        startY: 28,

        styles: {
            fontSize: 6,
            cellPadding: 2
        },

        headStyles: {
            fontSize: 6
        }

    });


    doc.save(
        "student-performance-report.pdf"
    );

}


/* GENERAL FILE DOWNLOAD */

function downloadFile(blob, fileName) {

    const url =
        URL.createObjectURL(blob);


    const link =
        document.createElement("a");


    link.href = url;

    link.download = fileName;


    document.body.appendChild(link);

    link.click();

    document.body.removeChild(link);


    URL.revokeObjectURL(url);

}